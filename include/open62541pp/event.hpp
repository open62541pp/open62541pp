#pragma once

#include <cstdint>
#include <string_view>

#include "open62541pp/types.hpp"
#include "open62541pp/ua/nodeids.hpp"

namespace opcua {

class Server;

/**
 * Create and trigger events.
 *
 * @see https://reference.opcfoundation.org/Core/Part3/v105/docs/4.7
 * @see https://reference.opcfoundation.org/Core/Part5/v105/docs/6.4.2
 *
 * @note
 * Before open62541 v1.5, an event is backed by a node representation, see id() and release().
 * Since v1.5, the properties are collected and the event is created in trigger().
 * The severity defaults to 1 and the message defaults to the BrowseName of the source node,
 * or to "Event" if no source node is provided. Both can be overridden with writeSeverity()
 * and writeMessage(), respectively.
 */
class Event {
public:
#if UAPP_OPEN62541_VER_LE(1, 4)
    explicit Event(Server& connection, const NodeId& eventType = ObjectTypeId::BaseEventType);
#else
    explicit Event(Server& connection, NodeId eventType = ObjectTypeId::BaseEventType);
#endif

    ~Event();

    Event(const Event&) = default;
    Event(Event&&) noexcept = default;

    Event& operator=(const Event&) = delete;
    Event& operator=(Event&&) noexcept = delete;

    /// Get the server instance.
    Server& connection() noexcept {
        return *connection_;
    }

    /// Get the server instance.
    const Server& connection() const noexcept {
        return *connection_;
    }

#if UAPP_OPEN62541_VER_LE(1, 4)
    /// Get the NodeId of the underlying node representation.
    /// @note Only available up to open62541 v1.4, events have no node representation since v1.5.
    const NodeId& id() const noexcept {
        return id_;
    }
#endif

    /// Set the source name (optional).
    Event& writeSourceName(std::string_view sourceName);

    /// Set the time of the event (UTC).
    Event& writeTime(DateTime time);

    /// Set the urgency/priority of the event from 1 (lowest) to 1000 (highest).
    Event& writeSeverity(uint16_t severity);

    /// Set a human-readable and localizable text description of the event.
    Event& writeMessage(const LocalizedText& message);

    /// Set an event property (e.g. a field of a custom event type).
    /// @param propertyName Name of the property.
    ///   Up to open62541 v1.4, only plain BrowseNames of properties are supported.
    ///   Since v1.5, the name is a browse path (SimpleAttributeOperand expression) relative to
    ///   the EventType, e.g. `/1:Truck/Wheel` for a nested field. A leading `/` is optional and
    ///   prepended if missing, i.e. `Severity` and `/Severity` address the same field.
    ///   The namespace index of `propertyName` is used as default namespace index for path
    ///   elements that do not specify one explicitly.
    /// @param value Value of the property.
    Event& writeProperty(const QualifiedName& propertyName, const Variant& value);

    /// Trigger the event.
    /// @param originId Origin node of the event (requires `EventNotifier` attribute)
    /// @return Unique `EventId` generated by server
    ByteString trigger(const NodeId& originId = ObjectId::Server);

#if UAPP_OPEN62541_VER_LE(1, 4)
    /// Release the ownership of the event and return the NodeId of the node representation.
    /// After calling this, the event is no longer valid.
    /// @note Only available up to open62541 v1.4, events have no node representation since v1.5.
    [[nodiscard]] NodeId release() noexcept;
#endif

private:
    Server* connection_;
#if UAPP_OPEN62541_VER_LE(1, 4)
    NodeId id_;
#else
    NodeId eventType_;
    KeyValueMap props_;
#endif
};

#if UAPP_OPEN62541_VER_LE(1, 4)
/// @relates Event
/// @note Only available up to open62541 v1.4, events have no node representation since v1.5.
bool operator==(const Event& lhs, const Event& rhs) noexcept;

/// @relates Event
/// @note Only available up to open62541 v1.4, events have no node representation since v1.5.
bool operator!=(const Event& lhs, const Event& rhs) noexcept;
#endif

}  // namespace opcua
